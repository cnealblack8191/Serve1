import { useRef, useState } from "react";
import {
  ExternalLink,
  FileText,
  FolderPlus,
  Link2,
  Loader2,
  Paperclip,
  Trash2,
  Upload,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { SharePointBrowser } from "./SharePointBrowser";
import { useEci } from "@/lib/eci/store";
import { useRecordDocuments, type RecordTarget } from "@/lib/sharepoint/useDocuments";
import {
  GENERIC_DOCUMENT_LABELS,
  RECORD_TYPE_LABELS,
  type BrowseItem,
} from "@/lib/sharepoint/types";

const ORIGIN_LABEL: Record<string, string> = {
  linked: "Linked",
  uploaded: "Uploaded",
  generated: "Generated by Serve One",
  communication: "Communication",
};

/**
 * "Documents associated with this record" — the single panel used across CRM
 * clients, opportunities, bids, jobs, work orders and invoices. Files stay in
 * SharePoint; the app stores durable references, so the same file can be
 * associated with several records without being copied.
 */
export function DocumentsPanel({
  target,
  title,
  description,
  labels = GENERIC_DOCUMENT_LABELS as readonly string[],
}: {
  target: RecordTarget;
  title?: string;
  description?: string;
  labels?: readonly string[];
}) {
  const { currentUser } = useEci();
  const { connected, location, documents, isLoading, attach, detach, upload, ensureFolder } =
    useRecordDocuments(target);

  const [browseOpen, setBrowseOpen] = useState(false);
  const [linkOpen, setLinkOpen] = useState(false);
  const [label, setLabel] = useState<string>(labels[0] ?? "Other");
  const [linkName, setLinkName] = useState("");
  const [linkUrl, setLinkUrl] = useState("");
  const fileInput = useRef<HTMLInputElement>(null);

  const recordLabel = RECORD_TYPE_LABELS[target.recordType].toLowerCase();

  const attachBrowsed = (item: BrowseItem) => {
    attach.mutate({
      recordType: target.recordType,
      recordId: target.recordId,
      label,
      linkedBy: currentUser,
      item: {
        itemId: item.id.startsWith("preview:") ? "" : item.id,
        name: item.name,
        extension: item.extension,
        webUrl: item.webUrl,
        folderPath: item.path,
        modifiedAt: item.modifiedAt,
        modifiedBy: item.modifiedBy,
      },
    });
    setBrowseOpen(false);
  };

  const onPickFile = async (file: File) => {
    const buf = await file.arrayBuffer();
    let binary = "";
    const bytes = new Uint8Array(buf);
    for (let i = 0; i < bytes.length; i += 1) binary += String.fromCharCode(bytes[i] ?? 0);
    upload.mutate({
      fileName: file.name,
      contentBase64: btoa(binary),
      label,
      uploadedBy: currentUser,
    });
  };

  return (
    <div className="eci-card overflow-hidden">
      <div className="flex flex-wrap items-start justify-between gap-3 border-b border-border px-6 py-4">
        <div>
          <p className="font-medium">
            {title ?? `Documents associated with this ${recordLabel}`}
          </p>
          <p className="text-xs text-muted-foreground">
            {description ??
              (connected
                ? "Stored in SharePoint and available to everyone on this record."
                : "SharePoint is not connected yet — associations are saved now and files sync once Microsoft 365 is connected.")}
          </p>
          {location ? (
            <p className="mt-1 font-mono text-[11px] text-muted-foreground">
              {location.folderPath}
            </p>
          ) : null}
        </div>
        <div className="flex flex-wrap gap-2">
          <Select value={label} onValueChange={setLabel}>
            <SelectTrigger className="h-9 w-40">
              <SelectValue placeholder="Label" />
            </SelectTrigger>
            <SelectContent>
              {labels.map((l) => (
                <SelectItem key={l} value={l}>
                  {l}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
          <Button variant="outline" size="sm" onClick={() => setBrowseOpen(true)}>
            <Paperclip className="mr-2 size-4" /> Attach existing
          </Button>
          <Button variant="outline" size="sm" onClick={() => setLinkOpen(true)}>
            <Link2 className="mr-2 size-4" /> Add link
          </Button>
          <Button
            variant="outline"
            size="sm"
            onClick={() => fileInput.current?.click()}
            disabled={upload.isPending}
          >
            {upload.isPending ? (
              <Loader2 className="mr-2 size-4 animate-spin" />
            ) : (
              <Upload className="mr-2 size-4" />
            )}
            Upload
          </Button>
          <input
            ref={fileInput}
            type="file"
            className="hidden"
            onChange={(e) => {
              const file = e.target.files?.[0];
              if (file) void onPickFile(file);
              e.target.value = "";
            }}
          />
          <Button
            variant="outline"
            size="sm"
            onClick={() => ensureFolder.mutate()}
            disabled={ensureFolder.isPending}
          >
            <FolderPlus className="mr-2 size-4" /> Open folder
          </Button>
        </div>
      </div>

      {isLoading ? (
        <div className="flex items-center gap-2 px-6 py-8 text-sm text-muted-foreground">
          <Loader2 className="size-4 animate-spin" /> Loading documents…
        </div>
      ) : documents.length === 0 ? (
        <p className="px-6 py-8 text-center text-sm text-muted-foreground">
          No documents associated with this {recordLabel} yet. Attach an existing SharePoint file,
          add a link, or upload one.
        </p>
      ) : (
        <ul className="divide-y divide-black/5">
          {documents.map((d) => (
            <li key={d.linkId} className="flex items-center gap-3 px-6 py-3">
              <FileText className="size-5 shrink-0 text-muted-foreground" />
              <div className="min-w-0 flex-1">
                <p className="truncate text-sm font-medium">
                  {d.name}
                  {d.label ? (
                    <span className="ml-2 rounded bg-eci-amber/15 px-1.5 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-eci-copper">
                      {d.label}
                    </span>
                  ) : null}
                </p>
                <p className="text-xs text-muted-foreground">
                  {[
                    ORIGIN_LABEL[d.origin] ?? d.origin,
                    d.extension,
                    d.linkedBy,
                    d.modifiedAt,
                  ]
                    .filter(Boolean)
                    .join(" · ")}
                  {d.alsoLinkedTo.length > 0
                    ? ` · also on ${d.alsoLinkedTo
                        .map((r) => RECORD_TYPE_LABELS[r.recordType].toLowerCase())
                        .join(", ")}`
                    : ""}
                </p>
              </div>
              {d.webUrl ? (
                <Button asChild variant="ghost" size="sm">
                  <a href={d.webUrl} target="_blank" rel="noopener noreferrer">
                    <ExternalLink className="mr-1.5 size-3.5" /> Open
                  </a>
                </Button>
              ) : (
                <span className="text-xs text-muted-foreground">Pending sync</span>
              )}
              <Button
                variant="ghost"
                size="sm"
                aria-label={`Remove ${d.name}`}
                onClick={() => detach.mutate(d.linkId)}
              >
                <Trash2 className="size-3.5" />
              </Button>
            </li>
          ))}
        </ul>
      )}

      <Dialog open={browseOpen} onOpenChange={setBrowseOpen}>
        <DialogContent className="max-w-3xl">
          <DialogHeader>
            <DialogTitle>Attach an existing document</DialogTitle>
            <DialogDescription>
              Browse the company SharePoint library and attach a file to this {recordLabel}. The
              file stays where it is — it is only referenced here.
            </DialogDescription>
          </DialogHeader>
          <div className="max-h-[60vh] overflow-y-auto">
            <SharePointBrowser
              {...(location?.folderPath ? { initialPath: location.folderPath } : {})}
              title="Company document library"
              onAttach={attachBrowsed}
            />
          </div>
        </DialogContent>
      </Dialog>

      <Dialog open={linkOpen} onOpenChange={setLinkOpen}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Add a document link</DialogTitle>
            <DialogDescription>
              Paste a SharePoint or OneDrive link to associate it with this {recordLabel}.
            </DialogDescription>
          </DialogHeader>
          <div className="space-y-4">
            <div className="space-y-2">
              <Label htmlFor="doc-name">Document name</Label>
              <Input
                id="doc-name"
                value={linkName}
                onChange={(e) => setLinkName(e.target.value)}
                placeholder="Addendum 2.pdf"
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="doc-url">Link</Label>
              <Input
                id="doc-url"
                value={linkUrl}
                onChange={(e) => setLinkUrl(e.target.value)}
                placeholder="https://ecinc.sharepoint.com/..."
              />
            </div>
          </div>
          <DialogFooter>
            <Button
              disabled={!linkName.trim() || !/^https?:\/\//i.test(linkUrl.trim())}
              onClick={() => {
                attach.mutate({
                  recordType: target.recordType,
                  recordId: target.recordId,
                  label,
                  linkedBy: currentUser,
                  item: { name: linkName.trim(), webUrl: linkUrl.trim() },
                });
                setLinkName("");
                setLinkUrl("");
                setLinkOpen(false);
              }}
            >
              Add link
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}
